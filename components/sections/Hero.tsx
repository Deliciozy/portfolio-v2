type Brand =
  | "baidu"
  | "multi"
  | "autoark"
  | "automind";

const brands: Brand[] = [
  "baidu",
  "multi",
  "autoark",
  "automind",
];

function BrandLogo({
  brand,
}: {
  brand: Brand;
}) {
  if (brand === "autoark") {
    return <AutoArkLogo />;
  }

  if (brand === "automind") {
    return <AutomindLogo />;
  }

  if (brand === "baidu") {
    return (
      <img
        src="/images/home/baidu-cloud-logo.svg"
        alt="Baidu AI Cloud"
        className={`${logoStyles.logo} ${logoStyles.baidu}`}
        draggable={false}
      />
    );
  }

  return (
    <img
      src="/images/home/multi-ai-logo.svg"
      alt="Multi-AI"
      className={`${logoStyles.logo} ${logoStyles.multi}`}
      draggable={false}
    />
  );
}

function LogoSet({
  copy,
}: {
  copy: number;
}) {
  return (
    <div
      className={logoStyles.group}
      aria-hidden={
        copy === 0
          ? undefined
          : true
      }
    >
      {brands.map(
        (brand) => (
          <div
            className={
              logoStyles.slot
            }
            key={`${copy}-${brand}`}
          >
            <BrandLogo
              brand={brand}
            />
          </div>
        )
      )}
    </div>
  );
}

